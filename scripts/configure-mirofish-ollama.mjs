#!/usr/bin/env node
/**
 * Point MiroFish backend at local Ollama (OpenAI-compatible API).
 * Backs up existing MiroFish/.env before overwriting.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const MIROFISH = path.resolve(__dirname, "../../MiroFish");
const ENV_PATH = path.join(MIROFISH, ".env");
const BACKUP_PATH = path.join(MIROFISH, ".env.backup-before-ollama");

const MODEL = process.env.LLM_MODEL_NAME || "qwen2.5:7b";
const BASE_URL = process.env.LLM_BASE_URL || "http://127.0.0.1:11434/v1";

function parseEnv(content) {
  const vars = {};
  for (const line of content.split(/\r?\n/)) {
    const m = line.match(/^([A-Z][A-Z0-9_]*)=(.*)$/);
    if (m) vars[m[1]] = m[2];
  }
  return vars;
}

function readExisting() {
  if (!fs.existsSync(ENV_PATH)) return {};
  return parseEnv(fs.readFileSync(ENV_PATH, "utf8"));
}

function writeOllamaEnv(existing) {
  const zepKey = existing.ZEP_API_KEY || process.env.ZEP_API_KEY || "";
  const maxRounds = existing.OASIS_DEFAULT_MAX_ROUNDS || process.env.OASIS_DEFAULT_MAX_ROUNDS || "40";
  const body = `# Auto-generated by configure-mirofish-ollama.mjs — local Ollama for report-only
LLM_API_KEY=ollama
LLM_BASE_URL=${BASE_URL}
LLM_MODEL_NAME=${MODEL}
LLM_FALLBACK_MODELS=

ZEP_API_KEY=${zepKey}

OASIS_DEFAULT_MAX_ROUNDS=${maxRounds}
FLASK_DEBUG=False
REPORT_AGENT_MAX_TOOL_CALLS=2
REPORT_AGENT_MIN_TOOL_CALLS=1
REPORT_AGENT_MAX_REFLECTION_ROUNDS=1
OLLAMA_MAX_TOKENS=2048
OLLAMA_CONNECTION_RETRIES=5
OLLAMA_RETRY_DELAY_SEC=10
`;
  fs.writeFileSync(ENV_PATH, body, "utf8");
  return { model: MODEL, baseUrl: BASE_URL, zepKey };
}

export function backupMirofishEnv() {
  if (fs.existsSync(ENV_PATH) && !fs.existsSync(BACKUP_PATH)) {
    fs.copyFileSync(ENV_PATH, BACKUP_PATH);
    console.log("Backed up MiroFish/.env → .env.backup-before-ollama");
  } else if (fs.existsSync(ENV_PATH)) {
    fs.copyFileSync(ENV_PATH, BACKUP_PATH);
  }
}

export function restoreMirofishEnv() {
  if (fs.existsSync(BACKUP_PATH)) {
    fs.copyFileSync(BACKUP_PATH, ENV_PATH);
    console.log("Restored MiroFish/.env from backup");
    return true;
  }
  return false;
}

export function configureMirofishOllama() {
  if (!fs.existsSync(path.join(MIROFISH, "backend"))) {
    throw new Error(`MiroFish not found at ${MIROFISH}`);
  }
  backupMirofishEnv();
  const existing = readExisting();
  const cfg = writeOllamaEnv(existing);
  console.log(`MiroFish .env → Ollama (${cfg.model} @ ${cfg.baseUrl})`);
  return cfg;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  try {
    configureMirofishOllama();
  } catch (e) {
    console.error(e.message);
    process.exit(1);
  }
}
