#!/usr/bin/env node
/**
 * Fetch Dodo checkout/supported_countries and emit src/shared/dodo-billing-countries.ts
 *
 * Usage: node scripts/generate-dodo-billing-countries.mjs
 * Env: DODO_PAYMENTS_API_KEY (or DOdo_api.txt)
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

function loadApiKey() {
  if (process.env.DODO_PAYMENTS_API_KEY?.trim()) return process.env.DODO_PAYMENTS_API_KEY.trim();
  for (const credPath of [
    join(dirname(fileURLToPath(import.meta.url)), "../../../atlas-webxr/DOdo_api.txt"),
    "D:/AI/atlas-webxr/DOdo_api.txt",
  ]) {
    try {
      const text = readFileSync(credPath, "utf8");
      const match = text.match(/Test_mode API Key\s*=\s*(\S+)/);
      if (match?.[1]) return match[1];
    } catch {
      // try next
    }
  }
  throw new Error("Set DODO_PAYMENTS_API_KEY");
}

const apiKey = loadApiKey();
const base = process.env.DODO_PAYMENTS_ENV === "live_mode"
  ? "https://live.dodopayments.com"
  : "https://test.dodopayments.com";

const response = await fetch(`${base}/checkout/supported_countries`, {
  headers: { Authorization: `Bearer ${apiKey}` },
});
if (!response.ok) {
  throw new Error(`Dodo supported_countries failed (${response.status})`);
}
/** @type {string[]} */
const codes = await response.json();
if (!Array.isArray(codes) || codes.length === 0) {
  throw new Error("Dodo supported_countries returned no data");
}

const display = new Intl.DisplayNames(["en"], { type: "region" });
const countries = codes
  .map((code) => {
    const normalized = String(code).trim().toUpperCase();
    if (!/^[A-Z]{2}$/.test(normalized)) return null;
    let name;
    try {
      name = display.of(normalized) || normalized;
    } catch {
      name = normalized;
    }
    return { code: normalized, name };
  })
  .filter(Boolean)
  .sort((a, b) => a.name.localeCompare(b.name, "en"));

const outPath = join(dirname(fileURLToPath(import.meta.url)), "../src/shared/dodo-billing-countries.ts");
const generatedAt = new Date().toISOString().slice(0, 10);
const contents = `/** Auto-generated by scripts/generate-dodo-billing-countries.mjs on ${generatedAt}. Do not edit manually. */
export type BillingCountryOption = { code: string; name: string };

/** ISO 3166-1 alpha-2 codes supported by Dodo Payments checkout (source: GET /checkout/supported_countries). */
export const DODO_BILLING_COUNTRIES: BillingCountryOption[] = ${JSON.stringify(countries, null, 2)};

const DODO_COUNTRY_CODES = new Set(DODO_BILLING_COUNTRIES.map((row) => row.code));

export function billingCountryOptions(
  provider: "dodo" | "zoho" | null | undefined
): BillingCountryOption[] {
  if (provider === "zoho") return [{ code: "IN", name: "India" }];
  return DODO_BILLING_COUNTRIES;
}

export function isSupportedBillingCountry(
  code: string,
  provider: "dodo" | "zoho" | null | undefined = "dodo"
): boolean {
  const normalized = typeof code === "string" ? code.trim().toUpperCase() : "";
  if (!/^[A-Z]{2}$/.test(normalized)) return false;
  if (provider === "zoho") return normalized === "IN";
  return DODO_COUNTRY_CODES.has(normalized);
}

export function formatBillingCountryLabel(option: BillingCountryOption): string {
  return \`\${option.code} — \${option.name}\`;
}
`;

writeFileSync(outPath, contents, "utf8");
console.log(`Wrote ${countries.length} countries to ${outPath}`);
