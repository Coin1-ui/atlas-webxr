let backendProc = null;
let envBackup = "";

function readKeyFile(fileName) {
  const p = path.join(KEY_DIR, fileName);
  if (!fs.existsSync(p)) return null;
  const line = fs
    .readFileSync(p, "utf8")
    .split(/\r?\n/)
    .map((l) => l.trim())
    .find((l) => l.length > 8);
  return line || null;
}

function loadProviders() {
  const loaded = [];
  for (const p of PROVIDERS) {
    const key = readKeyFile(p.file);
    if (key) loaded.push({ ...p, key });
    else console.warn(`Skip ${p.name}: missing or empty ${path.join(KEY_DIR, p.file)}`);
  }
  if (!loaded.length) {
    throw new Error(`No API keys found in ${KEY_DIR}`);
  }
  return loaded;
}

function readZepKey() {
  if (!fs.existsSync(ENV_PATH)) return process.env.ZEP_API_KEY || "";
  const line = fs
    .readFileSync(ENV_PATH, "utf8")
    .split(/\r?\n/)
    .find((l) => l.startsWith("ZEP_API_KEY="));
  return line ? line.slice("ZEP_API_KEY=".length).trim() : "";
}

function writeEnv({ llmKey, baseUrl, model, zepKey }) {
  const body = `# Auto-generated by run-mirofish-multi-api.mjs — do not commit
LLM_API_KEY=${llmKey}
LLM_BASE_URL=${baseUrl}
LLM_MODEL_NAME=${model}
LLM_FALLBACK_MODELS=

ZEP_API_KEY=${zepKey}

OASIS_DEFAULT_MAX_ROUNDS=${MAX_ROUNDS}
FLASK_DEBUG=False
REPORT_AGENT_MAX_TOOL_CALLS=2
REPORT_AGENT_MAX_REFLECTION_ROUNDS=1
`;
  fs.writeFileSync(ENV_PATH, body, "utf8");
  return { llmKey, baseUrl, model, zepKey };
}

function backendEnv(provider, zepKey) {
  return {
    ...process.env,
    PYTHONIOENCODING: "utf-8",
    LLM_API_KEY: provider.key,
    LLM_BASE_URL: provider.baseUrl,
    LLM_MODEL_NAME: provider.model,
    LLM_FALLBACK_MODELS: "",
    ZEP_API_KEY: zepKey,
    OASIS_DEFAULT_MAX_ROUNDS: String(MAX_ROUNDS),
    FLASK_DEBUG: "False",
    REPORT_AGENT_MAX_TOOL_CALLS: "2",
    REPORT_AGENT_MAX_REFLECTION_ROUNDS: "1",
  };
}

function backupEnv() {
  if (fs.existsSync(ENV_PATH)) envBackup = fs.readFileSync(ENV_PATH, "utf8");
}

function restoreEnv() {
  if (envBackup) fs.writeFileSync(ENV_PATH, envBackup, "utf8");
}

async function sleep(ms) {
  return new Promise((r) => setTimeout(r, ms));
}

function isRetryable(err) {
  const msg = String(err?.message || err);
  return /429|quota|rate.?limit|402|insufficient|credit|503|timeout|ECONNRESET|fetch failed/i.test(msg);
}

async function apiHealthy() {
  try {
    const res = await fetch(`${API}/health`, { signal: AbortSignal.timeout(4000) });
    return res.ok;
  } catch {
    return false;
  }
}

function stopBackend() {
  if (backendProc && !backendProc.killed) {
    backendProc.kill();
    backendProc = null;
  }
}

/** Kill any process listening on MiroFish port (stale backend keeps old Gemini config). */
async function killStaleBackendPort() {
  if (process.platform !== "win32") return;
  try {
    const { execSync } = await import("node:child_process");
    const out = execSync(`netstat -ano | findstr :5001`, { encoding: "utf8" });
    const pids = new Set();
    for (const line of out.split(/\r?\n/)) {
      const m = line.match(/LISTENING\s+(\d+)/);
      if (m) pids.add(m[1]);
    }
    for (const pid of pids) {
      try {
        execSync(`taskkill /F /PID ${pid}`, { stdio: "ignore" });
        console.log(`Killed stale process on :5001 (pid ${pid})`);
      } catch {
        /* ignore */
      }
    }
    if (pids.size) await sleep(2000);
  } catch {
    /* port free */
  }
}

async function waitForBackend(timeoutMs = 180000) {
  const start = Date.now();
  while (Date.now() - start < timeoutMs) {
    if (await apiHealthy()) return true;
    await sleep(2000);
    process.stdout.write(".");
  }
  return false;
}

async function startBackend(provider, zepKey) {
  stopBackend();
  await killStaleBackendPort();
  await sleep(2500);
  const backendDir = path.join(MIROFISH, "backend");
  const env = backendEnv(provider, zepKey);
  writeEnv({
    llmKey: provider.key,
    baseUrl: provider.baseUrl,
    model: provider.model,
    zepKey,
  });
  backendProc = spawn("uv run python run.py", {
    cwd: backendDir,
    stdio: "ignore",
    windowsHide: true,
    shell: true,
    env,
  });
  const ok = await waitForBackend();
  if (!ok) throw new Error("MiroFish backend not ready on " + API);
}

async function ensureBackend(provider, zepKey) {
  stopBackend();
  await sleep(2000);
  await startBackend(provider, zepKey);
}

async function verifyLlm(provider, zepKey) {
  await ensureBackend(provider, zepKey);
  console.log(`  LLM probe: ${provider.baseUrl} · ${provider.model}`);
  try {
    const res = await fetch(`${provider.baseUrl}/chat/completions`, {
      method: "POST",
      headers: {
        "Content-Type": "application/json",
        Authorization: `Bearer ${provider.key}`,
        ...(provider.name === "OpenRouter"
          ? { "HTTP-Referer": "https://atlas-ar.local", "X-Title": "Atlas AR MiroFish" }
          : {}),
      },
      body: JSON.stringify({
        model: provider.model,
        messages: [{ role: "user", content: "Reply with OK only." }],
        max_tokens: 8,
      }),
      signal: AbortSignal.timeout(60000),
    });
    if (!res.ok) {
      const t = await res.text();
      throw new Error(`${res.status}: ${t.slice(0, 200)}`);
    }
    console.log("  LLM probe OK");
    return true;
  } catch (e) {
    console.warn(`  LLM probe failed: ${e.message}`);
    return false;
  }
}

async function api(method, urlPath, body, isForm = false) {
  const opts = { method, headers: {} };
  if (isForm) opts.body = body;
  else if (body) {
    opts.headers["Content-Type"] = "application/json";
    opts.body = JSON.stringify(body);
  }
  const res = await fetch(`${API}${urlPath}`, opts);
  const text = await res.text();
  let json;
  try {
    json = JSON.parse(text);
  } catch {
    json = { raw: text };
  }
  if (!res.ok) throw new Error(`${method} ${urlPath} → ${res.status}: ${text.slice(0, 500)}`);
  return json;
}

async function poll(label, fn, maxAttempts, timeoutLabel) {
  for (let i = 0; i < maxAttempts; i++) {
    const st = await fn();
    if (st) return st;
    if (i > 0 && i % 6 === 0) {
      process.stdout.write(`\n  ${label} (${Math.round((i * POLL_MS) / 60000)}m)…`);
    }
    process.stdout.write(".");
    await sleep(POLL_MS);
  }
  throw new Error(`${timeoutLabel} timeout`);
}

function saveCheckpoint(meta) {
  const checkpointPath = path.join(ROOT, "docs/atlas-ar/mirofish/runs/CHECKPOINT-live-run.json");
  fs.mkdirSync(path.dirname(checkpointPath), { recursive: true });
  fs.writeFileSync(checkpointPath, JSON.stringify(meta, null, 2));
}

async function runSimulationWithProvider(provider, zepKey) {
  console.log(`\n=== Provider: ${provider.name} (${provider.model}) ===`);
  await ensureBackend(provider, zepKey);
  console.log(` backend ready · ${provider.baseUrl} · ${provider.model}`);

  const form = new FormData();
  const blob = new Blob([fs.readFileSync(SEED, "utf8")], { type: "text/markdown" });
  form.append("files", blob, "SEED-ATLAS-AR.md");
  form.append("simulation_requirement", REQUIREMENT);
  form.append("project_name", "Atlas AR GTM — UI/UX + marketing + sales");

  console.log("1/5 Ontology + upload…");
  const ont = await api("POST", "/api/graph/ontology/generate", form, true);
  const projectId = ont.data?.project_id;
  if (!projectId) throw new Error("No project_id");

  console.log("2/5 Build graph…");
  const build = await api("POST", "/api/graph/build", { project_id: projectId });
  await poll(
    "Graph",
    async () => {
      const st = await api("GET", `/api/graph/task/${build.data?.task_id}`);
      if (st.data?.status === "completed") return st.data;
      if (st.data?.status === "failed") throw new Error(st.data?.error || "Graph failed");
      return null;
    },
    180,
    "Graph",
  );
  console.log("\n done");

  console.log("3/5 Create simulation…");
  const simCreate = await api("POST", "/api/simulation/create", { project_id: projectId });
  const simulationId = simCreate.data?.simulation_id;
  if (!simulationId) throw new Error("No simulation_id");

  console.log("4/5 Prepare agents…");
  const prep = await api("POST", "/api/simulation/prepare", {
    simulation_id: simulationId,
    parallel_profile_count: 5,
  });
  await poll(
    "Prepare",
    async () => {
      const st = await api("POST", "/api/simulation/prepare/status", {
        task_id: prep.data?.task_id,
        simulation_id: simulationId,
      });
      if (st.data?.status === "ready" || st.data?.already_prepared) return st.data;
      if (st.data?.status === "failed") throw new Error(st.data?.error || "Prepare failed");
      return null;
    },
    180,
    "Prepare",
  );
  console.log("\n done");

  console.log(`5/5 Run simulation (${MAX_ROUNDS} rounds)…`);
  await api("POST", "/api/simulation/start", {
    simulation_id: simulationId,
    platform: "parallel",
    max_rounds: MAX_ROUNDS,
  });
  await poll(
    "Simulation",
    async () => {
      const st = await api("GET", `/api/simulation/${simulationId}/run-status`);
      if (st.data?.status === "completed" || st.data?.runner_status === "completed") return st.data;
      if (st.data?.status === "failed") throw new Error(st.data?.error || "Simulation failed");
      return null;
    },
    720,
    "Simulation",
  );
  console.log("\n simulation complete:", simulationId);

  const outDir = path.join(ROOT, "docs/atlas-ar/mirofish/runs", new Date().toISOString().replace(/[:.]/g, "-"));
  fs.mkdirSync(outDir, { recursive: true });
  fs.writeFileSync(
    path.join(outDir, "meta.json"),
    JSON.stringify(
      {
        projectId,
        simulationId,
        maxRounds: MAX_ROUNDS,
        simulationProvider: provider.name,
        simulationModel: provider.model,
        requirement: REQUIREMENT,
        reportSkipped: SKIP_REPORT,
      },
      null,
      2,
    ),
  );

  const checkpoint = {
    status: SKIP_REPORT ? "simulation_complete" : "pending_report",
    simulationId,
    projectId,
    reportPending: SKIP_REPORT,
    reportWith: "ollama",
    simulationProvider: provider.name,
    simulationModel: provider.model,
    runDir: path.relative(ROOT, outDir).replace(/\\/g, "/"),
    rounds: MAX_ROUNDS,
    updatedAt: new Date().toISOString(),
    resumeReport:
      "Set MiroFish .env to Ollama (LLM_BASE_URL=http://127.0.0.1:11434/v1, LLM_API_KEY=ollama), start backend, then: " +
      `MIROFISH_SIMULATION_ID=${simulationId} MIROFISH_PROJECT_ID=${projectId} node scripts/resume-mirofish-report.mjs`,
  };
  saveCheckpoint(checkpoint);

  console.log("\nCheckpoint:", path.join(ROOT, "docs/atlas-ar/mirofish/runs/CHECKPOINT-live-run.json"));
  console.log("Run dir:", outDir);
  if (SKIP_REPORT) {
    console.log("\nReport SKIPPED — generate locally with Ollama when ready:");
    console.log(checkpoint.resumeReport);
  }
  return { projectId, simulationId, outDir, provider: provider.name };
}

async function main() {
  if (!fs.existsSync(SEED)) throw new Error("Missing seed: " + SEED);
  if (!fs.existsSync(MIROFISH)) throw new Error("Clone MiroFish to " + MIROFISH);

  const zepKey = readZepKey();
  if (!zepKey) throw new Error("ZEP_API_KEY missing in MiroFish/.env");

  const providers = loadProviders();
  backupEnv();

  // Optional: Ollama-only simulation when all cloud keys are exhausted
  if (process.env.MIROFISH_OLLAMA_SIM === "1") {
    const ollamaModel = process.env.OLLAMA_MODEL_NAME || "qwen2.5:7b";
    providers.length = 0;
    providers.push({
      name: "Ollama",
      key: "ollama",
      baseUrl: "http://127.0.0.1:11434/v1",
      model: ollamaModel,
      file: "(ollama)",
    });
  }

  console.log("Atlas AR MiroFish — multi-API simulation");
  console.log("Key dir:", KEY_DIR);
  console.log("Providers:", providers.map((p) => p.name).join(", "));
  console.log("Rounds:", MAX_ROUNDS);
  console.log("Skip report (Ollama later):", SKIP_REPORT);

  let lastErr;
  for (const provider of providers) {
    try {
      if (!SKIP_PROBE) {
        const probed = await verifyLlm(provider, zepKey);
        if (!probed) {
          console.warn(`${provider.name} skipped (LLM probe failed)`);
          continue;
        }
      } else {
        console.log(`Skipping LLM probe for ${provider.name} (MIROFISH_SKIP_PROBE=1)`);
      }
      await runSimulationWithProvider(provider, zepKey);
      return;
    } catch (e) {
      lastErr = e;
      console.error(`\n${provider.name} failed:`, e.message);
      if (!isRetryable(e)) {
        console.warn("Non-retryable error — trying next provider anyway…");
      } else {
        console.warn("Trying next provider…");
      }
    }
  }
  throw lastErr || new Error("All providers failed");
}

function cleanup() {
  stopBackend();
  restoreEnv();
}

process.on("SIGINT", () => {
  cleanup();
  process.exit(130);
});
process.on("exit", cleanup);

main().catch((e) => {
  console.error("\nFailed:", e.message);
  process.exit(1);
});
